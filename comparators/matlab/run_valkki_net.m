function status = run_valkki_net(matPath, outDir, quality, dependencyRoot)
% run_valkki_net  Thin adapter for the authors' unmodified Network-CMA code.
%
% The active algorithm is called directly from the official authors'
% repository at external/NetworkWideAdaptiveBurstDetection, pinned to commit
% 9de22b0c2dde0dce29adfa207245e15d1f3805a4. This adapter only:
%   1. converts the project's spikeTime.mat representation into the cell
%      array of independent spike trains expected by CalculateCMANoRound;
%   2. calls CalculateCMANoRound('net',...) without changing its logic; and
%   3. serializes the returned per-input-train bursts and statistics.
%
% Important: Välkki et al.'s "network-wide" method pools within-train ISIs
% to estimate one common CMA burst/tail threshold, then applies that common
% threshold to every input train. It does not return a second-stage series
% of synchronized network-burst intervals. No N-unit overlap rule is used.

if nargin < 2 || isempty(outDir), outDir = pwd; end
if nargin < 3 || isempty(quality)
    quality = struct('snr_lo',1.2,'snr_hi',25,'fr_min',0.8+eps(0.8),'min_spikes',2);
end
if exist(outDir,'dir') ~= 7, mkdir(outDir); end

root = fileparts(mfilename('fullpath'));
if nargin < 4 || isempty(dependencyRoot)
    dependencyRoot = fullfile(fileparts(fileparts(root)),'external_dependencies');
end
authorRoot = fullfile(dependencyRoot,'NetworkWideAdaptiveBurstDetection');
requiredAuthorFiles = { ...
    'CalculateCMANoRound.m','getCMAinfo.m','getISIinfo.m', ...
    'skw2alpha.m','alphas2ths.m','DetectBurstNoRound.m'};
assert(exist(authorRoot,'dir')==7, ...
    'Missing authors'' NetworkWideAdaptiveBurstDetection checkout: %s',authorRoot);
for i = 1:numel(requiredAuthorFiles)
    sourcePath = fullfile(authorRoot,requiredAuthorFiles{i});
    assert(exist(sourcePath,'file')==2,'Missing original Välkki source: %s',sourcePath);
end

originalPath = path;
pathCleanup = onCleanup(@() path(originalPath));
addpath(authorRoot);
resolved = which('CalculateCMANoRound');
assert(strcmpi(resolved,fullfile(authorRoot,'CalculateCMANoRound.m')), ...
    'CalculateCMANoRound resolved to an unexpected file: %s',resolved);

% This is common study preprocessing, not part of the detector. The paper
% explicitly permits the analyzed network to be any chosen set of spike
% trains. Every retained spike-sorted cluster is one independent input train.
[SpikeTimes, IDs, Regions, Electrodes, Clusters, durMs] = ...
    spiketime_to_cells(matPath,quality.snr_lo,quality.snr_hi, ...
    quality.fr_min,quality.min_spikes);
nUnits = numel(SpikeTimes);

% The sole detector call: authors' source, unmodified, Network-CMA mode.
[BurstInfoN,CMAinfoN] = CalculateCMANoRound('net',SpikeTimes,IDs,durMs);

eventRows = cell(0,10);
for u = 1:height(BurstInfoN)
    starts = BurstInfoN.BurstStarts{u};
    ends = BurstInfoN.BurstEnds{u};
    labels = BurstInfoN.TypeOfSpike{u};
    for b = 1:numel(starts)
        eventRows(end+1,:) = {Electrodes{u},Clusters(u),Regions{u}, ... %#ok<AGROW>
            starts(b),ends(b),ends(b)-starts(b),sum(labels==b),u, ...
            IDs{u},'Valkki_NetworkCMA'};
    end
end
eventNames = {'Electrode','Cluster','Region','burst_start_ms','burst_end_ms', ...
    'burst_duration_ms','num_spikes','unit_id','author_input_id','Method'};
if isempty(eventRows)
    events = cell2table(cell(0,numel(eventNames)),'VariableNames',eventNames);
else
    events = cell2table(eventRows,'VariableNames',eventNames);
end
writetable(events,fullfile(outDir,'valkki_network_cma_perunit_bursts.csv'));

unitSummary = table(string(Electrodes(:)),Clusters(:),string(Regions(:)), ...
    (1:nUnits)',string(IDs(:)),BurstInfoN.SpikeCount,BurstInfoN.SpikeRate, ...
    BurstInfoN.BurstCount,BurstInfoN.BurstRate,BurstInfoN.BurstDuration, ...
    BurstInfoN.SpikesInBurst,BurstInfoN.BurstSpikeRatio,BurstInfoN.ISIinBurst, ...
    'VariableNames',{'Electrode','Cluster','Region','unit_id','author_input_id', ...
    'spike_count','spikes_per_min','burst_count','bursts_per_min', ...
    'mean_burst_duration_ms','mean_spikes_per_burst','burst_spike_ratio', ...
    'mean_isi_in_burst_ms'});
writetable(unitSummary,fullfile(outDir,'valkki_network_cma_unit_summary.csv'));

settings = table("Valkki_NetworkCMA_original", ...
    "https://github.com/kerstinlenk/NetworkWideAdaptiveBurstDetection.git", ...
    "9de22b0c2dde0dce29adfa207245e15d1f3805a4",nUnits, ...
    "one common threshold estimated from pooled within-train ISIs", ...
    "per-input-train burst intervals; no native synchronized network-event series", ...
    CMAinfoN.BurstThreshold,CMAinfoN.TailThreshold,CMAinfoN.BurstAlpha, ...
    CMAinfoN.TailAlpha,quality.snr_lo,quality.snr_hi,quality.fr_min, ...
    quality.min_spikes,false, ...
    'VariableNames',{'detector','source_repository','source_commit','n_input_units', ...
    'network_wide_definition','native_output_semantics','burst_threshold_ms', ...
    'tail_threshold_ms','burst_alpha','tail_alpha','preprocessing_snr_min', ...
    'preprocessing_snr_max','preprocessing_firing_rate_min_hz', ...
    'preprocessing_minimum_spikes','custom_overlap_rule_used'});
writetable(settings,fullfile(outDir,'detector_settings.csv'));

status = struct('n_input_units',nUnits,'n_burst_active_units', ...
    sum(BurstInfoN.BurstCount>0),'n_unit_bursts',height(events), ...
    'burst_threshold_ms',CMAinfoN.BurstThreshold, ...
    'tail_threshold_ms',CMAinfoN.TailThreshold, ...
    'custom_overlap_rule_used',false);
fprintf(['Valkki Network-CMA: input units %d | burst-active %d | ' ...
    'per-unit bursts %d | shared burst/tail thresholds %.3f/%.3f ms | ' ...
    'no synchronized network-event stage\n'],nUnits,status.n_burst_active_units, ...
    height(events),CMAinfoN.BurstThreshold,CMAinfoN.TailThreshold);
end
